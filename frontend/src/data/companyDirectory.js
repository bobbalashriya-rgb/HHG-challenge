/**
 * Resolves a user's free-form input (e.g. "Infosys" or "Apple" or "tcs")
 * to the exact Yahoo Finance ticker symbol (e.g. "INFY.NS", "AAPL", "TCS.NS").
 */
export function resolveTicker(input) {
    if (!input || typeof input !== 'string') return '';
    const clean = input.trim();
    const lower = clean.toLowerCase();

    // 1. Exact ticker match (e.g. "AAPL" or "INFY.NS")
    const exactTicker = COMPANY_DIRECTORY.find(c => c.ticker.toLowerCase() === lower);
    if (exactTicker) return exactTicker.ticker;

    // 2. Exact alias match (e.g. "infosys", "tcs", "apple", "reliance")
    const aliasMatch = COMPANY_DIRECTORY.find(c => c.aliases.includes(lower));
    if (aliasMatch) return aliasMatch.ticker;

    // 3. Substring match on company name
    const nameMatch = COMPANY_DIRECTORY.find(c => c.name.toLowerCase().includes(lower) || c.shortName.toLowerCase().includes(lower));
    if (nameMatch) return nameMatch.ticker;

    // 4. Default: Return uppercase trimmed input
    return clean.toUpperCase();
}

/**
 * Searches the directory for matches on query, market, and sector.
 */
export function searchDirectory(query = '', market = 'All', sector = 'All') {
    const q = query.trim().toLowerCase();

    return COMPANY_DIRECTORY.filter(company => {
        // Market filter
        if (market === 'India (NSE)' && company.country !== 'India') return false;
        if (market === 'US (NASDAQ/NYSE)' && company.country !== 'USA') return false;

        // Sector filter
        if (sector !== 'All' && company.sector !== sector) return false;

        // Query filter
        if (!q) return true;
        return (
            company.ticker.toLowerCase().includes(q) ||
            company.name.toLowerCase().includes(q) ||
            company.shortName.toLowerCase().includes(q) ||
            company.aliases.some(a => a.includes(q)) ||
            company.description.toLowerCase().includes(q)
        );
    });
}

